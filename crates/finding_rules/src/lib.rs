/// Look up a rule by its numeric id (`GF-NNNN`).
pub fn by_id(id: &str) -> Option<&'static Rule> {
    RULES.iter().find(|rule| rule.id == id)
}

/// Look up a rule by its slug (`govfuzz.<area>/<name>`).
pub fn by_slug(slug: &str) -> Option<&'static Rule> {
    RULES.iter().find(|rule| rule.slug == slug)
}

/// Pick the most specific rule id for a finding given its classification and
/// the captured Ada exception name. Returns `None` when no mapping applies and
/// callers should fall back to a generic finding id.
pub fn derive_rule_id(
    classification: Option<&str>,
    exception_name: Option<&str>,
) -> Option<&'static str> {
    let classification = classification.unwrap_or("").to_ascii_lowercase();
    let exception = exception_name
        .map(|name| name.to_ascii_uppercase())
        .unwrap_or_default();

    // A failed Ada 2012 contract (Pre/Post/Type_Invariant) or `pragma Assert` raises
    // Assertion_Error / Assert_Failure under -gnata. Report it as a contract violation
    // (GF-557) regardless of how the handler classified it — a contract firing is a
    // more specific, more actionable finding than a generic unhandled exception.
    if exception.contains("ASSERT_FAILURE") || exception.contains("ASSERTION_ERROR") {
        return Some("GF-557");
    }

    if classification == "explicit_raise" {
        return Some("GF-106");
    }
    if classification == "swallowed_user" {
        return Some("GF-105");
    }
    if classification == "swallowed_predefined" {
        return Some(match exception.as_str() {
            "CONSTRAINT_ERROR" => "GF-102",
            "STORAGE_ERROR" => "GF-103",
            "TASKING_ERROR" => "GF-104",
            _ => "GF-105",
        });
    }
    if classification == "unhandled" {
        return Some("GF-101");
    }

    None
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn rule_ids_are_unique() {
        let mut ids: Vec<&str> = RULES.iter().map(|rule| rule.id).collect();
        ids.sort();
        let initial_len = ids.len();
        ids.dedup();
        assert_eq!(ids.len(), initial_len, "duplicate rule ids in RULES");
    }

    #[test]
    fn rule_slugs_are_unique() {
        let mut slugs: Vec<&str> = RULES.iter().map(|rule| rule.slug).collect();
        slugs.sort();
        let initial_len = slugs.len();
        slugs.dedup();
        assert_eq!(slugs.len(), initial_len, "duplicate rule slugs in RULES");
    }

    #[test]
    fn every_rule_has_a_cwe() {
        for rule in RULES {
            assert!(
                rule.cwe.starts_with("CWE-"),
                "rule {} has unexpected cwe format: {}",
                rule.id,
                rule.cwe
            );
        }
    }

    #[test]
    fn cwe_top_25_places_are_in_range() {
        for rule in RULES {
            if let Some(place) = rule.cwe_top_25 {
                assert!(
                    (1..=25).contains(&place),
                    "rule {} has out-of-range cwe_top_25={}",
                    rule.id,
                    place
                );
            }
        }
    }

    #[test]
    fn security_severity_is_in_range() {
        for rule in RULES {
            assert!(
                (0.0..=10.0).contains(&rule.security_severity),
                "rule {} has out-of-range security_severity={}",
                rule.id,
                rule.security_severity
            );
        }
    }

    #[test]
    fn derive_rule_id_maps_unhandled_to_101() {
        assert_eq!(derive_rule_id(Some("unhandled"), None), Some("GF-101"));
    }

    #[test]
    fn oom_rule_gf_209_is_registered() {
        // The synthesized RSS-limit OOM report (fuzz.rs) tags findings GF-209, so
        // it must resolve to a real catalog rule (#386).
        let rule = by_id("GF-209").expect("GF-209 OOM rule must exist");
        assert_eq!(rule.cwe, "CWE-789");
        assert!(rule.name.to_lowercase().contains("memory"));
    }

    #[test]
    fn derive_rule_id_routes_swallowed_predefined_by_exception_name() {
        assert_eq!(
            derive_rule_id(Some("swallowed_predefined"), Some("CONSTRAINT_ERROR")),
            Some("GF-102")
        );
        assert_eq!(
            derive_rule_id(Some("swallowed_predefined"), Some("STORAGE_ERROR")),
            Some("GF-103")
        );
        assert_eq!(
            derive_rule_id(Some("swallowed_predefined"), Some("Tasking_Error")),
            Some("GF-104")
        );
        assert_eq!(
            derive_rule_id(Some("swallowed_predefined"), Some("PROGRAM_ERROR")),
            Some("GF-105")
        );
    }

    #[test]
    fn temporal_stack_rule_gf_211_is_registered_with_temporal_cwe() {
        // A temporal stack error (stack-use-after-return/-scope, #29) must map to
        // the expired-pointer-dereference class (CWE-825), NOT the spatial
        // stack-buffer-overflow CWE-121 that GF-203 carries.
        let rule = by_id("GF-211").expect("GF-211 temporal-stack rule must exist");
        assert_eq!(rule.cwe, "CWE-825");
        assert_ne!(rule.cwe, "CWE-121");
        // GF-203 must stay spatial-only.
        assert_eq!(by_id("GF-203").unwrap().cwe, "CWE-121");
    }

    #[test]
    fn derive_rule_id_returns_none_for_unknown_classification() {
        assert_eq!(derive_rule_id(Some("mystery"), None), None);
        assert_eq!(derive_rule_id(None, None), None);
    }

    #[test]
    fn derive_rule_id_maps_ada_contract_assertion_to_557() {
        // A failed Ada 2012 contract raises Assert_Failure / Assertion_Error under
        // -gnata; it must resolve to the contract-violation rule regardless of how the
        // handler classified it (propagated unhandled, or caught), and take precedence
        // over the generic GF-101 unhandled mapping.
        let rule = by_id("GF-557").expect("GF-557 contract-violation rule must exist");
        assert_eq!(rule.cwe, "CWE-617");
        assert_eq!(
            derive_rule_id(Some("unhandled"), Some("SYSTEM.ASSERTIONS.ASSERT_FAILURE")),
            Some("GF-557")
        );
        assert_eq!(
            derive_rule_id(Some("swallowed_user"), Some("Assertion_Error")),
            Some("GF-557")
        );
        // A non-assertion unhandled exception still maps to the generic GF-101.
        assert_eq!(
            derive_rule_id(Some("unhandled"), Some("STORAGE_ERROR")),
            Some("GF-101")
        );
    }

    #[test]
    fn by_id_and_by_slug_round_trip() {
        for rule in RULES {
            assert_eq!(by_id(rule.id).map(|r| r.slug), Some(rule.slug));
            assert_eq!(by_slug(rule.slug).map(|r| r.id), Some(rule.id));
        }
    }
}
