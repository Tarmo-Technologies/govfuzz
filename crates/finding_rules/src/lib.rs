/// Stable identifier for a finding's underlying rule.
///
/// Use the numeric form (`GF-NNNN`) as the primary key. The slug form is for
/// humans and for CodeQL-style consumers that prefer self-describing ids.
#[derive(Debug, Clone, Copy, PartialEq, Serialize)]
pub struct Rule {
    /// Numeric stable id, e.g. "GF-101". This is what callers should grep for
    /// and what SARIF carries as `ruleId`.
    pub id: &'static str,
    /// Human-readable slug, e.g. "govfuzz.ada/unhandled-exception". Emitted as
    /// a SARIF tag (`govfuzz.slug:...`) so consumers can filter on either.
    pub slug: &'static str,
    pub name: &'static str,
    pub description: &'static str,
    /// Most-specific Base/Variant CWE from the CWE-1003 view, e.g. "CWE-787".
    pub cwe: &'static str,
    /// Rank in the current MITRE CWE Top 25 (1 = most dangerous). `None` when
    /// the exact CWE is not on this year's list.
    pub cwe_top_25: Option<u32>,
    pub default_severity: Severity,
    pub default_confidence: Confidence,
    /// Numeric security severity in the SARIF / CodeQL / GitHub Code Scanning
    /// 0.0-10.0 range. Buckets: 9-10 critical, 7-8.9 high, 4-6.9 medium, < 4 low.
    pub security_severity: f32,
    pub references: &'static [&'static str],
    /// OWASP Top 10:2021 tag where applicable. Most fuzzing findings are
    /// non-web; leave `None` rather than forcing a fit.
    pub owasp_top_10: Option<&'static str>,
    pub cert_c: Option<&'static str>,
    pub cert_cpp: Option<&'static str>,
    pub misra_c: Option<&'static str>,
    pub misra_cpp: Option<&'static str>,
    /// ISO/IEC TR 24772-2:2020 three-letter vulnerability codes for Ada
    /// (primary code first, then any contributing-mechanism codes). Empty when
    /// no Ada-specific code applies. Example: `&["OYB", "XYZ"]` for "swallowed
    /// Constraint_Error from an array-index check" — OYB is the
    /// ignored-exception primary tag, XYZ marks the underlying index-check
    /// mechanism.
    pub iso_tr_24772_ada: &'static [&'static str],
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize)]
#[serde(rename_all = "lowercase")]
pub enum Severity {
    Critical,
    High,
    Medium,
    Low,
    Info,
}

impl Severity {
    pub fn as_str(self) -> &'static str {
        match self {
            Severity::Critical => "critical",
            Severity::High => "high",
            Severity::Medium => "medium",
            Severity::Low => "low",
            Severity::Info => "info",
        }
    }
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize)]
#[serde(rename_all = "lowercase")]
pub enum Confidence {
    High,
    Medium,
    Low,
}

impl Confidence {
    pub fn as_str(self) -> &'static str {
        match self {
            Confidence::High => "high",
            Confidence::Medium => "medium",
            Confidence::Low => "low",
        }
    }
}

