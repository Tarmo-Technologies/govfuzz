// Rule catalog for GovFuzz findings.
//
// Each rule has two identifiers: a stable numeric `id` (GF-NNNN, like Sonar's
// S-codes or gosec's G-codes) and a slug (`govfuzz.<area>/<name>`, like CodeQL's
// query ids). Both are emitted; the numeric id is the primary `ruleId` in SARIF
// and the slug is also tagged so SARIF consumers that prefer one or the other
// can switch view without losing data.
//
// CWE mappings target Base/Variant entries from the CWE-1003 Simplified Mapping
// view so they stay NVD-compatible. We never tag a Class (e.g. CWE-710), a
// Pillar (e.g. CWE-1000), or an organizational View on individual findings.
// CERT-C, CERT-C++, MISRA C, and ISO/IEC TR 24772-2 (Ada) identifiers are
// optional per rule and only populated where there's a defensible mapping.

use serde::Serialize;

